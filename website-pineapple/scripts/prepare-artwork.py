"""Responsive copies of the homepage artwork (frames, badges, mascot).

The hand-made artwork in public/images/royal-pineapple/ is one large file
each (the greeting frame was a 1.8 MB PNG). This writes AVIF and WebP copies
at a few widths next to each source (name-480.avif, name-480.webp, ...) and
regenerates src/components/landing/artworkAssets.ts, which the page uses to
build <picture> srcsets. Run it again after changing or adding artwork:

    python scripts/prepare-artwork.py
"""
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
PUBLIC = ROOT / 'public'
OUT_TS = ROOT / 'src' / 'components' / 'landing' / 'artworkAssets.ts'

# Source (under public/) -> widths to make. The source's own width is the cap.
SOURCES = {
    '/images/royal-pineapple/badge-frames/greeting-postcard-frame-v3.png': [480, 800, 1200, 1536],
    '/images/royal-pineapple/badge-frames/12-pool-club-frame.webp': [400, 800, 1200],
    '/images/royal-pineapple/badge-frames/13-evening-garden-frame.webp': [400, 800, 1200],
    '/images/royal-pineapple/badge-frames/14-grand-arrival-frame.webp': [300, 600, 1200],
    '/images/royal-pineapple/badges-v3/14-grand-arrival-badge.webp': [480, 800, 1000],
    '/images/royal-pineapple/royal-pineapple-mascot.webp': [180, 360, 480],
}

assets = {}
for source, widths in SOURCES.items():
    src = PUBLIC / source.lstrip('/')
    image = Image.open(src).convert('RGBA')
    stem = src.with_suffix('')
    made = []
    for width in sorted({min(w, image.width) for w in widths}):
        height = round(image.height * width / image.width)
        copy = image.resize((width, height), Image.LANCZOS) if width != image.width else image
        copy.save(f'{stem}-{width}.webp', 'WEBP', quality=80, method=6)
        copy.save(f'{stem}-{width}.avif', 'AVIF', quality=60, speed=4)
        made.append(width)
    base = source.rsplit('.', 1)[0]
    assets[source] = {
        'src': f'{base}-{made[-1]}.webp',
        'srcSet': ', '.join(f'{base}-{w}.webp {w}w' for w in made),
        'avifSrcSet': ', '.join(f'{base}-{w}.avif {w}w' for w in made),
        'width': image.width,
        'height': image.height,
    }
    sizes = [(PUBLIC / f'{base.lstrip("/")}-{w}.{ext}').stat().st_size // 1024 for w in made for ext in ('avif', 'webp')]
    print(source, made, f'{src.stat().st_size // 1024} KB source ->', sizes, 'KB (avif, webp per width)')

OUT_TS.write_text(
    '// Generated by scripts/prepare-artwork.py: responsive AVIF/WebP copies of the\n'
    '// homepage artwork, keyed by the original file. Do not edit by hand.\n'
    'export interface ArtworkAsset { src: string; srcSet: string; avifSrcSet: string; width: number; height: number }\n\n'
    f'export const artworkAssets: Record<string, ArtworkAsset> = {json.dumps(assets, indent=2)};\n',
    encoding='utf-8')
